# --- GSM8K (generative) --------------------------------------------------

def gen_gsm8k(lang):
    q_label, a_label = PROMPT_LABELS[lang]
    name = f"eu20_gsm8k_{lang.lower()}"
    if lang == "EN":
        path, cfg = EN_DATASETS["gsm8k"]
        ds_block = (
            f"dataset_path: {path}\n"
            f"dataset_name: {cfg}\n"
            f"test_split: test\n"
            f"fewshot_split: train\n"
        )
    else:
        ds_block = (
            _eurolingua_block(NON_EN_REPOS['gsm8k'], _gsm8k_files(lang))
            + "test_split: test\n"
            + "fewshot_split: train\n"
        )
    until_strings = ['"\\n\\n"', '"Question:"', '"Vraag:"', '"Kysymys:"', '"Въпрос:"']
    until_yaml = "[" + ", ".join(until_strings) + "]"
    body = (
        f"task: {name}\n"
        f"{ds_block}"
        f"output_type: generate_until\n"
        f"doc_to_text: !function _eu20_utils.gsm8k_doc_to_text_{lang}\n"
        f"doc_to_target: !function _eu20_utils.gsm8k_doc_to_target\n"
        f"generation_kwargs:\n"
        f"  max_gen_toks: 256\n"
        f"  do_sample: false\n"
        f"  until: {until_yaml}\n"
        f"process_results: !function _eu20_utils.gsm8k_process_results\n"
        f"metric_list:\n"
        f"  - metric: exact_match\n"
        f"    aggregation: mean\n"
        f"    higher_is_better: true\n"
        f"fewshot_config:\n"
        f"  sampler: first_n\n"
        f"num_fewshot: 5\n"
        f"metadata:\n"
        f"  version: 0.1\n"
    )
    _write(OUT_DIR / f"{name}.yaml", body)


# ----- main ---------------------------------------------------------------

def main():
    written = []
    for lang in LANGUAGES:
        ll = lang.lower()
        gen_arc_cf(lang); written.append(f"arc_challenge_{ll}_cf")
        gen_arc_mcf(lang); written.append(f"arc_challenge_{ll}_mcf")
        gen_hellaswag_cf(lang); written.append(f"hellaswag_{ll}_cf")
        gen_hellaswag_mcf(lang); written.append(f"hellaswag_{ll}_mcf")
        gen_tqa_mc1_cf(lang); written.append(f"truthfulqa_mc1_{ll}_cf")
        gen_tqa_mc1_mcf(lang); written.append(f"truthfulqa_mc1_{ll}_mcf")
        gen_tqa_mc2_cf(lang); written.append(f"truthfulqa_mc2_{ll}_cf")
        gen_gsm8k(lang); written.append(f"gsm8k_{ll}")

    print(f"Wrote {len(written)} yamls to {OUT_DIR}:")
    for w in written:
        print(f"  eu20_{w}.yaml")


if __name__ == "__main__":
    main()
