"""Emit EU20 task yamls for ARC-Challenge, HellaSwag, TruthfulQA, GSM8K
in {EN, NL, FI, BG} with both CF and MCF formulations where applicable.

Source of truth for the generated yamls in this directory. Run with:

    python eval/eu20_tasks/_generate_yamls.py

and commit the result. Adding a language or benchmark = edit the constants
below and re-run.
"""
import os
from pathlib import Path

# ----- scope --------------------------------------------------------------

LANGUAGES = ["EN", "NL", "FI", "BG"]   # subset of EU20 we care about
PROMPT_LABELS = {                       # (Question, Answer) per language
    "EN": ("Question", "Answer"),
    "NL": ("Vraag", "Antwoord"),
    "FI": ("Kysymys", "Vastaus"),
    "BG": ("Въпрос", "Отговор"),
}

# Eurolingua datasets live under one repo per benchmark; English isn't shipped
# (translations from EN), so EN yamls point at the upstream HF datasets.
# We load Eurolingua jsonl files via the generic `json` builder and full HF
# resolve URLs, which bypasses the custom loading script that newer datasets
# versions refuse to run.
NON_EN_REPOS = {
    "arc_challenge": "Eurolingua/arcx",
    "hellaswag":     "Eurolingua/hellaswagx",
    "truthfulqa":    "Eurolingua/truthfulqax",
    "gsm8k":         "Eurolingua/gsm8kx",
}


def _hf_url(repo, filename):
    return f"https://huggingface.co/datasets/{repo}/resolve/main/{filename}"


EN_DATASETS = {
    "arc_challenge": ("allenai/ai2_arc", "ARC-Challenge"),
    "hellaswag":     ("Rowan/hellaswag", None),
    "truthfulqa":    ("truthful_qa", "multiple_choice"),
    "gsm8k":         ("gsm8k", "main"),
}

OUT_DIR = Path(__file__).resolve().parent

HEADER = (
    "# Generated by _generate_yamls.py — do not edit by hand. "
    "Edit the generator and re-run.\n"
)

# ----- file-path helpers --------------------------------------------------

def _arc_files(lang):
    base = f"arc_challenge_{lang}"
    return {"train": f"{base}_train.jsonl",
            "validation": f"{base}_validation.jsonl",
            "test": f"{base}_test.jsonl"}


def _hellaswag_files(lang):
    base = f"hellaswag_{lang}"
    return {"train": f"{base}_train.jsonl",
            "validation": f"{base}_validation.jsonl"}


def _tqa_files(lang):
    return {"validation": f"truthfulqa_mc_{lang}_validation.jsonl"}


def _gsm8k_files(lang):
    base = f"gsm8k_{lang}"
    return {"train": f"{base}_train.jsonl",
            "test": f"{base}_test.jsonl"}


# ----- yaml writers -------------------------------------------------------

def _write(path, body):
    path.write_text(HEADER + body)


def _eurolingua_block(repo, files):
    """Return the dataset_path + dataset_kwargs YAML for a Eurolingua repo,
    using the `json` builder + full HF resolve URLs so we bypass the
    repo's custom loading script (which newer `datasets` versions refuse).
    """
    lines = ["dataset_path: json", "dataset_kwargs:", "  data_files:"]
    for split, fname in files.items():
        lines.append(f"    {split}: {_hf_url(repo, fname)}")
    return "\n".join(lines) + "\n"


# --- ARC-Challenge --------------------------------------------------------

def gen_arc_cf(lang):
    q_label, a_label = PROMPT_LABELS[lang]
    name = f"eu20_arc_challenge_{lang.lower()}_cf"
    if lang == "EN":
        path, cfg = EN_DATASETS["arc_challenge"]
        ds_block = (
            f"dataset_path: {path}\n"
            f"dataset_name: {cfg}\n"
            f"test_split: test\n"
            f"fewshot_split: train\n"
        )
    else:
        ds_block = (
            _eurolingua_block(NON_EN_REPOS['arc_challenge'], _arc_files(lang))
            + f"test_split: test\n"
            + f"fewshot_split: train\n"
        )
    body = (
        f"include: _eu20_base_cf.yaml\n"
        f"task: {name}\n"
        f"{ds_block}"
        f"doc_to_text: \"{q_label}: {{{{question}}}}\\n{a_label}:\"\n"
        f"doc_to_target: \"{{{{choices.label.index(answerKey)}}}}\"\n"
        f"doc_to_choice: \"{{{{choices.text}}}}\"\n"
        f"fewshot_config:\n"
        f"  sampler: first_n\n"
    )
    _write(OUT_DIR / f"{name}.yaml", body)


